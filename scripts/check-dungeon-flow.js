(async () => {
  const d = window.__IDLECOMBATZ__;
  if (!d?.ready) throw Error('Scene not ready');
  const results = [];
  const check = (v, name) => { if (!v) throw Error(name); results.push(name); };
  const settle = () => new Promise(r => setTimeout(r, 100));
  const click = sel => { const b = document.querySelector(sel); if (!b || b.disabled) throw Error(`Unavailable control ${sel}`); b.click(); };
  d.controller.startOver(); d.advance(0);
  check(d.simulation.unlockedFloor === 1 && d.simulation.actors.length === 13, 'new game starts at dungeon entrance');
  const s = d.simulation; s.gold = 5000;
  click('.bottom-nav [data-panel="upgrades"]'); await settle();
  click('[data-upgrade="atk"]'); await settle();
  check(s.levels.atk === 1 && s.gold === 4994, 'UI purchase charges gold and changes stats');
  for (let i = 0; i < 12; i++) for (const id of ['atk','hp','def']) if (s.levels[id] < 12) d.controller.buyUpgrade(id);
  s.hero.hp = s.hero.maxHp;
  click('[data-action="close-panel"]');
  click('.bottom-nav [data-panel="map"]'); await settle();
  check(document.querySelector('[data-room-id="0"]').disabled === false && document.querySelector('[data-room-id="5"]').disabled, 'map exposes only known rooms');
  click('[data-room-id="0"]'); await settle(); check(s.order?.kind === 'move', 'room control creates a destination order');
  d.advance(1); await settle(); check(s.order === null, 'arrived order automatically resumes exploration');
  d.advance(20); await settle();
  check(s.gold > 0 && s.roomsCleared > 0, 'automatic combat clears room');
  for(let i=0;i<60 && s.floor===1;i++) d.advance(3);
  check(s.floor===2 && s.clearedFloors.includes(1), 'loot and clear unlock next floor');
  check(s.navigationRecoveries===0, 'navigation never used recovery');
  d.controller.setProgression(false); const floor=s.floor;
  for(let i=0;i<60 && s.completedRuns<2;i++)d.advance(3);
  d.advance(3); check(s.floor===floor,'repeat setting stays on selected floor');
  d.controller.setProgression(true);
  for(let i=0;i<180 && s.mode!=='boss';i++) d.advance(2);
  await settle(); check(s.mode==='boss' && !document.querySelector('.boss-health').hidden,'boss begins inside Floor 3 with visible HUD');
  click('[data-action="retreat"]'); await settle(); check(s.hero.hp===0 && s.respawnIn>0,'retreat ends encounter and begins recovery');
  d.advance(6); check(s.hero.hp>0 && s.roomsCleared===0,'recovery starts a fresh floor');
  for(let i=0;i<180 && !s.bossDefeated;i++) d.advance(2);
  await settle(); check(s.bossDefeated && !document.querySelector('.secondary-tile').classList.contains('locked'),'boss defeat unlocks Slot II');
  for(let i=0;i<120 && s.floor!==4;i++)d.advance(2);
  await settle(); check(s.floor===4 && s.region==='crypt','Auto enters Moss Crypt');
  check(document.querySelector('#arena').dataset.loadError===undefined,'all production assets loaded');
  check(document.documentElement.scrollWidth===innerWidth,'portrait viewport has no horizontal overflow');
  const data=s.exportSave(); localStorage.setItem('idlecombatz.save',JSON.stringify(data)); window.__qaSaved=JSON.stringify(data);
  return {checks:results,floor:s.floor,runs:s.completedRuns,gold:s.gold,recoveries:s.navigationRecoveries,saveVersion:data.version};
})()
